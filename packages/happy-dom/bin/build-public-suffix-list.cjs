const FS = require('fs/promises');
const Path = require('path');
const { domainToASCII } = require('url');
const Prettier = require('prettier');
const PrettierConfig = require('../../../.prettierrc.cjs');
const Chalk = require('chalk').default;

const PUBLIC_SUFFIX_LIST_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';

/**
 * Parses both the ICANN and private sections of the Public Suffix List.
 *
 * @param {string} content List content.
 * @returns {{exact: string[], wildcard: string[], exception: string[]}} Rules.
 */
function parsePublicSuffixList(content) {
	for (const section of ['ICANN', 'PRIVATE']) {
		if (
			!content.includes(`// ===BEGIN ${section} DOMAINS===`) ||
			!content.includes(`// ===END ${section} DOMAINS===`)
		) {
			throw new Error(`Invalid Public Suffix List: missing ${section} section.`);
		}
	}

	const rules = { exact: [], wildcard: [], exception: [] };
	for (const line of content.split('\n')) {
		const rule = line.trim();
		if (!rule || rule.startsWith('//')) {
			continue;
		}
		const type = rule.startsWith('!') ? 'exception' : rule.startsWith('*.') ? 'wildcard' : 'exact';
		const domain = domainToASCII(
			type === 'exception' ? rule.slice(1) : type === 'wildcard' ? rule.slice(2) : rule
		).toLowerCase();
		if (!domain || !/^[a-z0-9_-]+(?:\.[a-z0-9_-]+)*$/.test(domain)) {
			throw new Error(`Invalid Public Suffix List rule: ${rule}`);
		}
		rules[type].push(domain);
	}
	if (!rules.exact.length || !rules.wildcard.length || !rules.exception.length) {
		throw new Error('Invalid Public Suffix List: missing rules.');
	}
	return rules;
}

/**
 * Downloads and generates bundled public suffix rules.
 */
async function main() {
	console.log(Chalk.bold(`Downloading Public Suffix List from ${PUBLIC_SUFFIX_LIST_URL}...`));
	const response = await fetch(PUBLIC_SUFFIX_LIST_URL, { signal: AbortSignal.timeout(30000) });
	if (!response.ok) {
		throw new Error(
			`Failed to download Public Suffix List: ${response.status} ${response.statusText}`
		);
	}
	const content = await response.text();
	const rules = parsePublicSuffixList(content);
	console.log(Chalk.gray('• Builds PublicSuffixList.ts'));
	const result = await Prettier.format(
		`// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.
//
// Generated by build-public-suffix-list.cjs. Do not edit manually.
// Source: ${PUBLIC_SUFFIX_LIST_URL}
export default {
	exact: new Set<string>(${JSON.stringify(rules.exact)}),
	wildcard: new Set<string>(${JSON.stringify(rules.wildcard)}),
	exception: new Set<string>(${JSON.stringify(rules.exception)})
};
`,
		{ ...PrettierConfig, parser: 'typescript' }
	);
	await FS.writeFile(Path.resolve(__dirname, '../src/cookie/PublicSuffixList.ts'), result, 'utf-8');
	console.log(Chalk.green('Finished'));
}

main();
