const Path = require('path');
const FS = require('fs/promises');
const packageJson = require('../package.json');
const Prettier = require('prettier');
const PrettierConfig = require('../../../.prettierrc.cjs');
const Chalk = require('chalk');

const CSS_PROPERTIES_URL =
	'https://chromium.googlesource.com/chromium/src/+/main/third_party/blink/renderer/core/css/css_properties.json5?format=TEXT';

const DEPRECATED_PROPERTIES = ['css-float'];

async function main() {
	console.log(Chalk.bold('Downloading CSS properties from Chromium...'));
	const response = await fetch(CSS_PROPERTIES_URL);

	if (!response.ok) {
		throw new Error(`Failed to download: ${response.status} ${response.statusText}`);
	}

	const base64 = await response.text();
	const content = Buffer.from(base64, 'base64').toString('utf-8');

	const json = content
		.replace(/\s*\/\/.*$/gm, '')
		.replace(/,(\s+)}/g, '$1}')
		.replace(/,(\s+)]/g, '$1]')
		.replace(/^\s+([a-zA-Z0-9_]+):/gm, '"$1":');

	const parsed = JSON.parse(json);
	const rules = parsed.data.map((line) => line.name);

	rules.push(...DEPRECATED_PROPERTIES);

	await Promise.all([writePropertyList(rules), writInterface(rules)]);

	console.log(Chalk.green('Finished'));
}

async function writePropertyList(rules) {
	console.log(Chalk.gray('• Builds CSSPropertyList.ts'));

	const ruleMap = {
		kebabCase: {},
		camelCase: {}
	};

	for (const rule of rules) {
		if (rule[0] !== '-') {
			const camelCaseRule = kebabToCamelCase(rule);
			ruleMap.kebabCase[rule] = camelCaseRule;
			ruleMap.camelCase[camelCaseRule] = rule;
		}
	}

	const result = await Prettier.format(
		`/**\n * This file is automatically generated by the "build-css-properties.cjs" script. Do not edit this file manually.\n */\nexport default ${JSON.stringify(ruleMap, null, 4)}`,
		{
			semi: false,
			parser: 'babel',
			...PrettierConfig
		}
	);
	const resultWithSemicolon = result.replace(/}\s*$/, '};\n');

	await FS.writeFile(
		Path.resolve('./src/css/declaration/CSSPropertyList.ts'),
		resultWithSemicolon,
		'utf-8'
	);
}

function kebabToCamelCase(text) {
	const parts = text.split('-');
	for (let i = 0, max = parts.length; i < max; i++) {
		parts[i] = i > 0 ? parts[i].charAt(0).toUpperCase() + parts[i].slice(1) : parts[i];
	}
	return parts.join('');
}

async function writInterface(rules) {
	console.log(Chalk.gray('• Builds ICSSStyleDeclaration.ts'));

	let interfaceString = '/**\n';
	interfaceString +=
		' * This file is automatically generated by the "build-css-properties.cjs" script. Do not edit this file manually.\n';
	interfaceString += ' */\n';
	interfaceString += 'export default interface ICSSStyleDeclaration {\n';

	for (let i = 0; i < rules.length; i++) {
		const rule = rules[i];
		if (rule[0] !== '-') {
			interfaceString += `\t${kebabToCamelCase(rule)}: string;\n`;
			if (rule.includes('-')) {
				interfaceString += `\t'${rule}': string;\n`;
			}
		}
	}

	interfaceString += '}\n';

	await FS.writeFile(
		Path.resolve('./src/css/declaration/ICSSStyleDeclaration.ts'),
		interfaceString,
		'utf-8'
	);
}

main();
